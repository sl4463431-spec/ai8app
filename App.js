const menuItems = [
  { id: "assistant", icon: "✦" },
  { id: "writing", icon: "✎" },
  { id: "video", icon: "▶" },
  { id: "image", icon: "▧" },
  { id: "voice", icon: "♫" },
  { id: "projects", icon: "▤" },
];

export default function App() {
  const [lang, setLang] = useState("ar");
  const [page, setPage] = useState("home");
  const [input, setInput] = useState("");
  const [result, setResult] = useState("");
  const [projects, setProjects] = useState([]);

  const t = translations[lang];

  function openPage(name) {
    setPage(name);
    setInput("");
    setResult("");
  }

  function generate() {
    if (!input.trim()) {
      Alert.alert(t.empty);
      return;
    }

    let answer = "";

    if (page === "assistant") {
      if (lang === "ar") {
        answer =
          "فكرتك: " + input +
          "\n\n1. حدد الهدف من الفكرة." +
          "\n2. قسّمها إلى خطوات صغيرة." +
          "\n3. ابدأ بنموذج أولي." +
          "\n4. اختبره وطوّره.";
      } else if (lang === "fr") {
        answer =
          "Votre idée : " + input +
          "\n\n1. Définissez votre objectif." +
          "\n2. Divisez-le en petites étapes." +
          "\n3. Créez un premier prototype." +
          "\n4. Testez-le et améliorez-le.";
      } else {
        answer =
          "Your idea: " + input +
          "\n\n1. Define your goal." +
          "\n2. Break it into small steps." +
          "\n3. Build a first prototype." +
          "\n4. Test and improve it.";
      }
    } else {
      if (lang === "ar") {
        answer =
          "عنوان مقترح:\n" + input +
          "\n\nنص مقترح:\nاكتشفوا فكرتنا الجديدة! نقدم لكم تجربة مميزة تجمع بين الإبداع والبساطة.";
      } else if (lang === "fr") {
        answer =
          "Titre proposé :\n" + input +
          "\n\nDécouvrez notre nouvelle idée ! Une expérience unique qui allie créativité et simplicité.";
      } else {
        answer =
          "Suggested title:\n" + input +
          "\n\nDiscover our new idea! We offer a unique experience combining creativity and simplicity.";
      }
    }

    setResult(answer + "\n\n" + t.demo);
  }

  function saveProject() {
    if (!result.trim()) {
      Alert.alert(t.empty);
      return;
    }

    setProjects((oldProjects) => [
      ...oldProjects,
      {
        id: Date.now().toString(),
        title: input.trim() || t.voice,
        content: result,
      },
    ]);

    Alert.alert(t.saved);
  }

  function speakText() {
    const textToSpeak = result || input;

    if (!textToSpeak.trim()) {
      Alert.alert(t.empty);
      return;
    }

    const speechLanguage =
      lang === "ar" ? "ar-SA" : lang === "fr" ? "fr-FR" : "en-US";

    Speech.stop();
    Speech.speak(textToSpeak, {
      language: speechLanguage,
      rate: 0.9,
    });
  }

  function renderHome() {
    return (
      <View>
        <View style={styles.hero}>
          <Text style={styles.logo}>AI8</Text>
          <Text style={styles.slogan}>{t.slogan}</Text>
          <Text style={styles.welcome}>{t.welcome}</Text>
          <Text style={styles.description}>{t.description}</Text>
        </View>

        <Text style={styles.sectionTitle}>AI8 TOOLS</Text>

        <View style={styles.grid}>
          {menuItems.map((item) => (
            <TouchableOpacity
              key={item.id}
              style={styles.menuCard}
              onPress={() => openPage(item.id)}
              activeOpacity={0.8}
            >
              <Text style={styles.menuIcon}>{item.icon}</Text>
              <Text style={styles.menuText}>{t[item.id]}</Text>
            </TouchableOpacity>
          ))}
        </View>
      </View>
    );
  }

  function renderProjects() {
    if (projects.length === 0) {
      return <Text style={styles.infoText}>{t.noProjects}</Text>;
    }

    return projects.map((project) => (
      <View key={project.id} style={styles.resultBox}>
        <Text style={styles.resultTitle}>{project.title}</Text>
        <Text style={styles.resultText}>{project.content}</Text>
      </View>
    ));
  }

  function renderPage() {
    if (page === "home") return renderHome();

    if (page === "projects") {
      return (
        <View>
          <Text style={styles.sectionTitle}>{t.projects}</Text>
          {renderProjects()}
        </View>
      );
    }

    if (page === "video" || page === "image") {
      return (
        <View style={styles.resultBox}>
          <Text style={styles.resultTitle}>{t[page]}</Text>
          <Text style={styles.infoText}>
            {page === "video" ? t.videoInfo : t.imageInfo}
          </Text>
        </View>
      );
    }

    return (
      <View>
        <Text style={styles.sectionTitle}>{t[page]}</Text>
        <TextInput
          style={styles.input}
          value={input}
          onChangeText={(value) => {
            setInput(value);
            setResult("");
          }}
          placeholder={t.input}
          placeholderTextColor="#8794AD"
          multiline
          textAlignVertical="top"
        />

        {page !== "voice" && (
          <TouchableOpacity style={styles.primaryButton} onPress={generate}>
            <Text style={styles.primaryButtonText}>{t.generate}</Text>
          </TouchableOpacity>
        )}

        {page === "voice" && (
          <TouchableOpacity style={styles.primaryButton} onPress={speakText}>
            <Text style={styles.primaryButtonText}>{t.speak}</Text>
          </TouchableOpacity>
        )}

        {!!result && (
          <View style={styles.resultBox}>
            <Text style={styles.resultTitle}>{t.result}</Text>
            <Text style={styles.resultText}>{result}</Text>

            <TouchableOpacity style={styles.secondaryButton} onPress={saveProject}>
              <Text style={styles.secondaryButtonText}>{t.save}</Text>
            </TouchableOpacity>

            <TouchableOpacity style={styles.secondaryButton} onPress={speakText}>
              <Text style={styles.secondaryButtonText}>{t.speak}</Text>
            </TouchableOpacity>
          </View>
        )}
      </View>
    );
  }

  return (
    <SafeAreaView style={styles.safeArea}>
      <StatusBar barStyle="light-content" backgroundColor="#071329" />

      <View style={styles.topBar}>
        <TouchableOpacity onPress={() => openPage("home")}>
          <Text style={styles.topLogo}>AI8</Text>
        </TouchableOpacity>

        <View style={styles.languageRow}>
          {["ar", "en", "fr"].map((code) => (
            <TouchableOpacity
              key={code}
              onPress={() => setLang(code)}
              style={[
                styles.languageButton,
                lang === code && styles.languageButtonActive,
              ]}
            >
              <Text style={styles.languageText}>{code.toUpperCase()}</Text>
            </TouchableOpacity>
          ))}
        </View>
      </View>

      <ScrollView contentContainerStyle={styles.content}>
        {renderPage()}

        {page !== "home" && (
          <TouchableOpacity
            style={styles.backButton}
            onPress={() => openPage("home")}
          >
            <Text style={styles.backButtonText}>← {t.back}</Text>
          </TouchableOpacity>
        )}
      </ScrollView>

      <View style={styles.footer}>
        <Text style={styles.footerText}>AI8 • {t.slogan}</Text>
      </View>
    </SafeAreaView>
  );
}

